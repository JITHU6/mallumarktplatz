/** Icons selectable for categories (stored as kebab-case keys in the database). */
export const CATEGORY_ICONS: Record<string, LucideIcon> = {
  utensils: UtensilsCrossed,
  "shopping-basket": ShoppingBasket,
  stethoscope: Stethoscope,
  calculator: Calculator,
  laptop: Laptop,
  building: Building2,
  plane: Plane,
  car: Car,
  sparkles: Sparkles,
  "spray-can": SprayCan,
  hammer: Hammer,
  "graduation-cap": GraduationCap,
  camera: Camera,
  briefcase: Briefcase,
  store: Store,
  scissors: Scissors,
  music: Music,
  baby: Baby,
  dumbbell: Dumbbell,
  "heart-pulse": HeartPulse,
  house: House,
  truck: Truck,
  shirt: Shirt,
  coffee: Coffee,
  languages: Languages,
  scale: Scale,
  wrench: Wrench,
  landmark: Landmark,
  palette: Palette,
  gem: Gem,
  flower: Flower2,
  "party-popper": PartyPopper,
};

export function CategoryIcon({ icon, className }: { icon: string | null | undefined; className?: string }) {
  const Icon = (icon && CATEGORY_ICONS[icon]) || Briefcase;
  return <Icon className={className} aria-hidden="true" />;
}
